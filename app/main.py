"""
FastAPI sidecar for MedCare ML Pipeline.

Provides HTTP endpoints for the Express backend to trigger daily rollover
and monthly retrain, and poll for run status. Runs inside the ML container
on port 8000.

Usage:
    uvicorn app.main:app --host 0.0.0.0 --port 8000
"""

from __future__ import annotations

import subprocess
import sys
import time
import uuid
from pathlib import Path

from fastapi import FastAPI, HTTPException
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel, ConfigDict, Field

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "db"))

ROOT = Path(__file__).resolve().parents[1]
PY = sys.executable

import runs as run_store  # noqa: E402

app = FastAPI(title="MedCare ML Pipeline API", version="1.0.0")


def _parse_date(value: str) -> str:
    """Validate a YYYY-MM-DD date string and return it normalized."""
    try:
        import datetime as _dt

        dt = _dt.date.fromisoformat(value)
    except ValueError as exc:
        raise HTTPException(
            status_code=422, detail=f"Invalid date '{value}' — expected YYYY-MM-DD"
        ) from exc
    return dt.isoformat()

app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_methods=["*"],
    allow_headers=["*"],
)


# ─── Run tracking ──────────────────────────────────────────────────────────────
# Run state is persisted in `pipeline_run` (see db/runs.py) rather than process
# memory so a sidecar restart does not lose in-flight/completed run history.

class RunResponse(BaseModel):
    """Trigger acknowledgement. JSON is camelCase to match the backend/frontend contract."""

    model_config = ConfigDict(populate_by_name=True)

    run_id: str = Field(alias="runId")
    status: str
    message: str
    as_of: str | None = Field(default=None, alias="asOf")


class RunStatusResponse(BaseModel):
    """Run status for polling. JSON is camelCase to match the backend contract."""

    model_config = ConfigDict(populate_by_name=True)

    run_id: str = Field(alias="runId")
    status: str
    triggered_by: str = Field(alias="triggeredBy")
    as_of: str | None = Field(default=None, alias="asOf")
    started_at: str = Field(alias="startedAt")
    finished_at: str | None = Field(default=None, alias="finishedAt")
    duration_seconds: float | None = Field(default=None, alias="durationSeconds")
    error: str | None = None
    steps_completed: list[str] = Field(default_factory=list, alias="stepsCompleted")


class DailyTriggerBody(BaseModel):
    """Trigger payload for the daily rollover.

    ``date`` is optional: when omitted the pipeline runs against
    ``pipeline_state.simulated_today`` (the normal advance-day flow). When
    provided, it re-executes the whole chain for that date without touching
    the simulated date (the retry-a-specific-date flow).
    """

    date: str | None = None
    triggered_by: str = "api"


# ─── Pipeline execution ────────────────────────────────────────────────────────

